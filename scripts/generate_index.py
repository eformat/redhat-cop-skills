#!/usr/bin/env python3
"""Generate the README skill index and the docs-site catalog from frontmatter.

Single source of truth = skills/*/SKILL.md frontmatter. This script rewrites
only the block between the GENERATED:INDEX markers in README.md, and emits
site-data/skills.json (gitignored build artifact) for docs/build_site.py.

--check mode compares instead of writing and exits 1 on drift (CI).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from skills_common import SkillError, load_all_skills, one_line, repo_root

START = "<!-- GENERATED:INDEX:START -->"
END = "<!-- GENERATED:INDEX:END -->"
HEADER = "<!-- Generated by scripts/generate_index.py — do not edit inside these markers. Run `make index`. -->"
DESC_TABLE_MAX = 240


def collect_skills() -> list[dict]:
    skills = []
    for s in load_all_skills():
        if "error" in s:
            raise SkillError(s["error"])
        meta = s["meta"]
        md = meta.get("metadata") or {}
        skills.append({
            "name": str(meta.get("name", s["dir_name"])),
            "description": one_line(meta.get("description", "")),
            "version": str(md.get("version", "")),
            "maturity": str(md.get("maturity", "")),
            "owner": str(md.get("owner", "")).lstrip("@"),
            "domain": str(md.get("domain", "")),
            "path": f"skills/{s['dir_name']}",
        })
    skills.sort(key=lambda x: x["name"])
    return skills


def render_table(skills: list[dict]) -> str:
    lines = [START, HEADER, ""]
    if not skills:
        lines += [
            "| Skill | Description | Version | Maturity | Owner |",
            "|---|---|---|---|---|",
            "| _No skills yet — be the first: see [CONTRIBUTING.md](CONTRIBUTING.md)_ | | | | |",
        ]
    else:
        lines += [
            "| Skill | Description | Version | Maturity | Owner |",
            "|---|---|---|---|---|",
        ]
        for s in skills:
            desc = s["description"]
            if len(desc) > DESC_TABLE_MAX:
                desc = desc[: DESC_TABLE_MAX - 1].rstrip() + "…"
            desc = desc.replace("|", "\\|")
            owner = f"[@{s['owner']}](https://github.com/{s['owner']})" if s["owner"] else ""
            lines.append(
                f"| [{s['name']}]({s['path']}/) | {desc} | {s['version']} | {s['maturity']} | {owner} |"
            )
    lines += ["", END]
    return "\n".join(lines)


def update_readme(skills: list[dict]) -> tuple[str, str]:
    """Returns (status, detail): 'ok' | 'missing-markers' | 'updated'."""
    readme = repo_root() / "README.md"
    text = readme.read_text(encoding="utf-8")
    block = render_table(skills)
    if START not in text or END not in text:
        return "missing-markers", f"README.md lacks {START} … {END} markers"
    pre = text[: text.index(START)]
    post = text[text.index(END) + len(END):]
    new_text = pre + block + post
    if new_text == text:
        return "ok", "README index up to date"
    readme.write_text(new_text, encoding="utf-8")
    return "updated", "README index regenerated"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="CI mode: exit 1 if README is stale")
    args = ap.parse_args()

    try:
        skills = collect_skills()
    except SkillError as exc:
        print(f"ERROR: {exc}")
        return 1

    if args.check:
        readme = (repo_root() / "README.md").read_text(encoding="utf-8")
        expected = render_table(skills)
        if START not in readme or END not in readme:
            print(f"ERROR: README.md is missing the {START} / {END} markers")
            return 1
        existing = readme[readme.index(START): readme.index(END) + len(END)]
        if existing != expected:
            print("ERROR: README skill index is stale — run `make index` and commit the result")
            return 1
        print(f"OK: README index up to date ({len(skills)} skill(s))")
        return 0

    status, detail = update_readme(skills)
    print(detail)
    if status == "missing-markers":
        return 1

    site_data = repo_root() / "site-data"
    site_data.mkdir(exist_ok=True)
    out = site_data / "skills.json"
    out.write_text(json.dumps(skills, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(repo_root())} ({len(skills)} skill(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
